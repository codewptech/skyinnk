import assert from "node:assert/strict";
import { mkdtemp, writeFile, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";
import prisma from "../server/utils/prisma.ts";
import {previewAcademicPublication,publishAcademicCourse,withdrawAcademicCourse} from "../server/utils/academic-publication.ts";
import {readAcademicAsset} from "../server/utils/academic-private-media.ts";
const url=new URL(process.env.DATABASE_URL||"");
assert.equal(url.hostname,"127.0.0.1"); assert.equal(url.port,"55432"); assert.equal(url.pathname,"/skyinnk_fixture"); assert.equal(process.env.DIRECT_URL,process.env.DATABASE_URL);
const root=await mkdtemp(join(tmpdir(),"skyinnk-academic-fixture-"));
const rejects=(fn,code)=>assert.rejects(fn,e=>e.code===code);
const guard=(fn,message)=>assert.rejects(fn,e=>String(e.message).includes('code: "23514"')&&String(e.message).includes(message));
try {
 const reviewer=await prisma.user.create({data:{auth0Id:"fixture|publication-reviewer"}});
 const editor=await prisma.user.create({data:{auth0Id:"fixture|publication-editor"}});
 const outsider=await prisma.user.create({data:{auth0Id:"fixture|publication-outsider"}});
 const c=await prisma.course.create({data:{sourceKey:"release-fixture-course",slug:"release-fixture-course",title:"Fictional approved course",summary:"Original fictional summary",audience:"Fixture learners"}});
 const subject=await prisma.subject.create({data:{key:"release-fixture-subject",name:"Fictional subject"}});
 await prisma.courseSubject.create({data:{courseId:c.id,subjectId:subject.id,isPrimary:true}});
 await prisma.courseEducator.createMany({data:[{courseId:c.id,userId:reviewer.id,permission:"REVIEWER"},{courseId:c.id,userId:editor.id,permission:"EDITOR"}]});
 const m=await prisma.module.create({data:{courseId:c.id,sourceKey:"release-fixture-module",title:"Original module",position:0}});
 const l=await prisma.lesson.create({data:{courseId:c.id,moduleId:m.id,sourceKey:"release-fixture-lesson",slug:"first",title:"Original lesson",position:0,overview:"Fictional overview",notesMarkdown:"## Example\nOriginal fictional notes."}});
 const bytes=Buffer.from("Fictional reviewed resource.\n"), hash=createHash("sha256").update(bytes).digest("hex");
 await writeFile(join(root,hash),bytes);
 const media=await prisma.mediaAsset.create({data:{provider:"LOCAL_PRIVATE",externalKey:hash,sha256:hash,mimeType:"text/plain",sizeBytes:bytes.length}});
 const res=await prisma.learningResource.create({data:{sourceKey:"release-fixture-file",title:"Fictional resource",mediaAssetId:media.id}});
 await prisma.lessonResource.create({data:{lessonId:l.id,resourceId:res.id,position:0}});
 await prisma.courseResource.create({data:{courseId:c.id,resourceId:res.id,position:0}});
 assert.equal(await prisma.courseRelease.count({where:{courseId:c.id,state:"ACTIVE"}}),0);
 await rejects(()=>previewAcademicPublication(outsider.id,c.id,root),"FORBIDDEN");
 const review=await previewAcademicPublication(editor.id,c.id,root);
 await rejects(()=>publishAcademicCourse(editor.id,c.id,review.digest,true,root),"FORBIDDEN");
 await rejects(()=>publishAcademicCourse(reviewer.id,c.id,review.digest,false,root),"INVALID");
 await writeFile(join(root,hash),Buffer.alloc(bytes.length,65));
 await rejects(()=>previewAcademicPublication(reviewer.id,c.id,root),"INVALID");
 await rm(join(root,hash)); await symlink(join(root,"missing"),join(root,hash));
 await assert.rejects(()=>readAcademicAsset(root,hash,bytes.length,"text/plain"));
 await rm(join(root,hash)); await writeFile(join(root,hash),bytes);
 assert.deepEqual(await readAcademicAsset(root,hash,bytes.length,"text/plain"),bytes);
 await prisma.lesson.update({where:{id:l.id},data:{notesMarkdown:"## Example\nUpdated fictional notes."}});
 await rejects(()=>publishAcademicCourse(reviewer.id,c.id,review.digest,true,root),"STALE");
 assert.equal(await prisma.courseRelease.count({where:{courseId:c.id}}),0);
 const corrected=await previewAcademicPublication(reviewer.id,c.id,root);
 const released=await publishAcademicCourse(reviewer.id,c.id,corrected.digest,true,root);
 assert.equal(released.version,1);
 assert.equal(released.id.split("-")[2][0],"7");
 const live=await prisma.courseRelease.findUniqueOrThrow({where:{id:released.id},include:{modules:{include:{lessons:{include:{resources:true}}}},resources:true,classifications:true}});
 assert.equal(live.state,"ACTIVE"); assert.equal(live.reviewedById,reviewer.id); assert.ok(live.rightsConfirmed);
 const published=live.modules[0].lessons[0];
 assert.equal(published.lessonId,l.id); assert.equal(published.notesMarkdown,"## Example\nUpdated fictional notes.");
 assert.equal(published.resources[0].sha256,hash); assert.equal(live.resources[0].sha256,hash);
 await guard(()=>prisma.publishedLesson.update({where:{id:published.id},data:{title:"Changed directly"}}),"academic_snapshot_immutable");
 await guard(()=>prisma.courseRelease.update({where:{id:released.id},data:{title:"Changed directly"}}),"academic_release_immutable");
 await guard(()=>prisma.course.update({where:{id:c.id},data:{slug:"changed"}}),"published_course_identity_immutable");
 await guard(()=>prisma.lesson.update({where:{id:l.id},data:{slug:"changed"}}),"published_lesson_identity_immutable");
 await guard(()=>prisma.course.update({where:{id:c.id},data:{archivedAt:new Date()}}),"withdraw_before_archive");
 await prisma.lesson.update({where:{id:l.id},data:{notesMarkdown:"NOT EDUCATOR APPROVED"}});
 await rejects(()=>previewAcademicPublication(reviewer.id,c.id,root),"INVALID");
 assert.equal((await prisma.publishedLesson.findUniqueOrThrow({where:{id:published.id}})).notesMarkdown,"## Example\nUpdated fictional notes.");
 console.log("PASS scoped author/reviewer, explicit attestation, stale draft, private byte/hash/symlink validation, immutable published snapshot and URL guards");
 await prisma.lesson.update({where:{id:l.id},data:{notesMarkdown:"## Example\nNew fictional revision."}});
 const next=await previewAcademicPublication(reviewer.id,c.id,root);
 const attempts=await Promise.allSettled([publishAcademicCourse(reviewer.id,c.id,next.digest,true,root),publishAcademicCourse(reviewer.id,c.id,next.digest,true,root)]);
 assert.equal(attempts.filter(x=>x.status==="fulfilled").length,1);
 assert.equal(attempts.filter(x=>x.status==="rejected"&&x.reason.code==="STALE").length,1);
 const active=await prisma.courseRelease.findFirstOrThrow({where:{courseId:c.id,state:"ACTIVE"}});
 assert.equal(active.version,2); assert.equal(await prisma.courseRelease.count({where:{courseId:c.id,state:"ACTIVE"}}),1);
 assert.equal((await prisma.courseRelease.findUniqueOrThrow({where:{id:released.id}})).state,"SUPERSEDED");
 await rejects(()=>withdrawAcademicCourse(editor.id,c.id,active.id),"FORBIDDEN");
 await rejects(()=>withdrawAcademicCourse(reviewer.id,c.id,released.id),"STALE");
 await withdrawAcademicCourse(reviewer.id,c.id,active.id);
 assert.equal(await prisma.courseRelease.count({where:{courseId:c.id,state:"ACTIVE"}}),0);
 assert.equal((await prisma.courseRelease.findUniqueOrThrow({where:{id:active.id}})).state,"WITHDRAWN");
 // Revert to the exact pre-first-publication draft. With no active release,
 // its previous digest must NOT authorize republishing after withdrawal.
 await prisma.lesson.update({where:{id:l.id},data:{notesMarkdown:"## Example\nUpdated fictional notes."}});
 await rejects(()=>publishAcademicCourse(reviewer.id,c.id,corrected.digest,true,root),"STALE");
 const fresh=await previewAcademicPublication(reviewer.id,c.id,root);
 assert.notEqual(fresh.digest,corrected.digest);
 const third=await publishAcademicCourse(reviewer.id,c.id,fresh.digest,true,root);
 assert.equal(third.version,3);
 await withdrawAcademicCourse(reviewer.id,c.id,third.id);
 await prisma.course.update({where:{id:c.id},data:{archivedAt:new Date()}});
 console.log("PASS concurrent atomic replacement, one active release, preserved history, stale withdrawal review, intentional republication and archive");
} finally { await prisma.$disconnect(); await rm(root,{recursive:true,force:true}); }
